// Get fonts by priority - first N fonts are loaded first
export function getPriorityFonts(count: number = 10): string[] {
  return googleFonts.slice(0, count);
}

// Get remaining fonts after priority
export function getRemainingFonts(priorityCount: number = 10): string[] {
  return googleFonts.slice(priorityCount);
}

